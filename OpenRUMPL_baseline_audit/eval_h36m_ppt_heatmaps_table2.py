#!/usr/bin/env python3
"""Evaluate official PPT heatmaps under the verified RUMPL Table-2 protocol.

PPT's released evaluator reports four-view MPJPE using its own triangulator.
This adapter additionally evaluates every 2/3/4-view subset with the exact
camera, target-coordinate, damaged-sequence, robust-ray, and action averaging
code used by our real-H36M RUMPL audit.
"""

from __future__ import annotations

import argparse
import itertools
import json
import pickle
from collections import defaultdict
from pathlib import Path

import h5py
import numpy as np

from eval_h36m_sparse_epipolar_topk import (
    ACTION_NAMES,
    KP_STAR,
    build_four_view_groups,
    camera_parameters,
    pixels_to_rays,
    robust_intersection,
    target_world_metres,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input-pkl", required=True)
    parser.add_argument("--prediction-h5", required=True)
    parser.add_argument("--views", type=int, nargs="+", default=[2, 3, 4])
    parser.add_argument("--irls-iterations", type=int, default=5)
    parser.add_argument("--limit-groups", type=int, default=0)
    parser.add_argument("--output", required=True)
    return parser.parse_args()


def summarize(
    errors: dict[str, dict[str, list[float]]],
    kp_errors: dict[str, list[float]],
) -> dict:
    output = {}
    for method, action_values in errors.items():
        per_action = {
            action: float(np.mean(values))
            for action, values in sorted(action_values.items())
        }
        flat = [
            value
            for action_group in action_values.values()
            for value in action_group
        ]
        output[method] = {
            "frame_weighted_all17_mm": float(np.mean(flat)),
            "action_equal_all17_mm": float(np.mean(list(per_action.values()))),
            "frame_weighted_kp_star_mm": float(np.mean(kp_errors[method])),
            "per_action_all17_mm": per_action,
        }
    return output


def main() -> None:
    args = parse_args()
    if any(n_views != 4 for n_views in args.views):
        raise ValueError(
            "The official H5 was generated by a four-view PPT forward pass. "
            "Selecting 2/3 heatmaps from it leaks the omitted views; use "
            "eval_h36m_ppt_variable_views.py for fair V2/V3 evaluation."
        )
    with open(args.input_pkl, "rb") as handle:
        records = pickle.load(handle)
    groups = build_four_view_groups(records)

    with h5py.File(args.prediction_h5, "r") as source:
        locations = np.asarray(source["locations"], dtype=np.float64)
        heatmaps = np.asarray(source["heatmaps"], dtype=np.float32)
    expected = len(groups) * 4
    if len(locations) != expected or len(heatmaps) != expected:
        raise RuntimeError(
            f"PPT output contains {len(locations)} views, expected {expected}"
        )
    locations = locations.reshape(len(groups), 4, 17, 3)
    heatmaps = heatmaps.reshape(len(groups), 4, 17, *heatmaps.shape[-2:])
    peak = heatmaps.reshape(len(groups), 4, 17, -1).max(axis=-1)

    results = {
        "input_pkl": args.input_pkl,
        "prediction_h5": args.prediction_h5,
        "complete_four_view_groups": len(groups),
        "protocol": "RUMPL Table-2 camera/action/damage/target evaluator",
        "results": {},
    }
    for n_views in args.views:
        work = [
            (group_index, combination)
            for group_index in range(len(groups))
            for combination in itertools.combinations(range(4), n_views)
        ]
        if args.limit_groups:
            work = work[: args.limit_groups]
        errors = defaultdict(lambda: defaultdict(list))
        kp_errors = defaultdict(list)
        for position, (group_index, combination) in enumerate(work, start=1):
            record_indices = [groups[group_index][view] for view in combination]
            group_records = [records[index] for index in record_indices]
            xy = locations[group_index, list(combination), :, :2]
            confidence_logits = peak[group_index, list(combination)]
            confidence = np.exp(
                confidence_logits - confidence_logits.max(axis=0, keepdims=True)
            )
            camera_data = [camera_parameters(record) for record in group_records]
            intrinsics = [item[0] for item in camera_data]
            rotations = [item[1] for item in camera_data]
            centers = np.stack([item[2] for item in camera_data])
            directions = np.stack(
                [
                    pixels_to_rays(xy[view], intrinsics[view], rotations[view])
                    for view in range(n_views)
                ]
            )
            target = target_world_metres(group_records[0])
            action = ACTION_NAMES[int(group_records[0]["action"])]
            for method, weights in (
                ("ppt_uniform_irls", np.ones_like(confidence)),
                ("ppt_peak_irls", confidence),
            ):
                prediction = np.stack(
                    [
                        robust_intersection(
                            centers,
                            directions[:, joint],
                            weights[:, joint],
                            args.irls_iterations,
                        )
                        for joint in range(17)
                    ]
                )
                joint_error = np.linalg.norm(
                    prediction - target, axis=-1
                ) * 1000.0
                errors[method][action].append(float(joint_error.mean()))
                kp_errors[method].append(
                    float(joint_error[list(KP_STAR)].mean())
                )
            if position % 500 == 0 or position == len(work):
                print(f"V{n_views}: {position}/{len(work)}", flush=True)
        summary = summarize(errors, kp_errors)
        results["results"][f"V{n_views}"] = {
            "views": n_views,
            "groups": len(work),
            "methods": summary,
        }
        for method, metrics in summary.items():
            print(
                f"V{n_views} {method}: "
                f"All={metrics['action_equal_all17_mm']:.3f} "
                f"KP*={metrics['frame_weighted_kp_star_mm']:.3f}",
                flush=True,
            )

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + ".tmp")
    temporary.write_text(
        json.dumps(results, indent=2) + "\n", encoding="utf-8"
    )
    temporary.replace(output)
    print(f"saved: {output}", flush=True)


if __name__ == "__main__":
    main()
